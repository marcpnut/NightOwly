-- Non-destructive normalized catalog migration from the imported public.streams table.
-- Keeps public.streams untouched; all new data is copied into sc_* tables.
-- Safe to re-run. Run as the streamcinema database owner.

BEGIN;

CREATE TABLE IF NOT EXISTS sc_languages (
  id smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code text NOT NULL UNIQUE,
  name text NOT NULL UNIQUE
);

INSERT INTO sc_languages(code, name) VALUES
