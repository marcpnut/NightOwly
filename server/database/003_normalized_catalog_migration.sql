CREATE TABLE IF NOT EXISTS sc_titles (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind text NOT NULL CHECK (kind IN ('movie','series','episode','live')),
  canonical_key text NOT NULL UNIQUE,
  tmdb_id text,
  release_year integer,
  original_title text NOT NULL,
  runtime_seconds integer,
  rating numeric(5,2),
  poster_url text,
  backdrop_url text,
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
  metadata_source text NOT NULL DEFAULT 'provider',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(kind, tmdb_id)
);
CREATE INDEX IF NOT EXISTS sc_titles_kind_title_idx ON sc_titles(kind, original_title);
CREATE INDEX IF NOT EXISTS sc_titles_tmdb_idx ON sc_titles(tmdb_id) WHERE tmdb_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS sc_title_translations (
  title_id bigint NOT NULL REFERENCES sc_titles(id) ON DELETE CASCADE,
  language_id smallint NOT NULL REFERENCES sc_languages(id),
  display_title text NOT NULL,
  description text,
  tagline text,
  trailer_id text,
  poster_url text,
  source text NOT NULL DEFAULT 'provider' CHECK (source IN ('provider','tmdb','manual')),
  updated_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY(title_id, language_id)
);

CREATE TABLE IF NOT EXISTS sc_categories (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  provider_key text NOT NULL DEFAULT 'xtream',
  kind text NOT NULL CHECK (kind IN ('movie','series','episode','live')),
  provider_category_id text NOT NULL,
  name text NOT NULL,
  UNIQUE(provider_key, kind, provider_category_id, name)
);
CREATE TABLE IF NOT EXISTS sc_category_languages (
  category_id bigint NOT NULL REFERENCES sc_categories(id) ON DELETE CASCADE,
  language_id smallint NOT NULL REFERENCES sc_languages(id),
  PRIMARY KEY(category_id, language_id)
);

CREATE TABLE IF NOT EXISTS sc_provider_streams (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  provider_key text NOT NULL DEFAULT 'xtream',
  kind text NOT NULL CHECK (kind IN ('movie','series','episode','live')),
  provider_id text NOT NULL,
  title_id bigint NOT NULL REFERENCES sc_titles(id),
  parent_provider_id text,
  language_id smallint REFERENCES sc_languages(id),
  provider_name text NOT NULL,
  stream_extension text,
  playback_path_template text,
  resolved_source_url text,
  resolved_source_saved_at timestamptz,
  resolved_source_failed_at timestamptz,
  active boolean NOT NULL DEFAULT true,
  first_seen_at timestamptz,
  last_seen_at timestamptz,
  UNIQUE(provider_key, kind, provider_id)
);
CREATE INDEX IF NOT EXISTS sc_provider_streams_title_idx ON sc_provider_streams(title_id, active);
CREATE INDEX IF NOT EXISTS sc_provider_streams_parent_idx ON sc_provider_streams(parent_provider_id) WHERE kind='episode';
CREATE INDEX IF NOT EXISTS sc_provider_streams_language_idx ON sc_provider_streams(language_id, active);

CREATE TABLE IF NOT EXISTS sc_stream_categories (
  stream_id bigint NOT NULL REFERENCES sc_provider_streams(id) ON DELETE CASCADE,
  category_id bigint NOT NULL REFERENCES sc_categories(id) ON DELETE CASCADE,
  PRIMARY KEY(stream_id, category_id)
);
CREATE INDEX IF NOT EXISTS sc_stream_categories_category_idx ON sc_stream_categories(category_id, stream_id);

CREATE TABLE IF NOT EXISTS sc_series_episodes (
  episode_title_id bigint PRIMARY KEY REFERENCES sc_titles(id) ON DELETE CASCADE,
  series_title_id bigint NOT NULL REFERENCES sc_titles(id) ON DELETE CASCADE,
  season_number integer NOT NULL,
  episode_number integer NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS sc_series_episodes_number_idx
  ON sc_series_episodes(series_title_id, season_number, episode_number)
  WHERE season_number > 0 AND episode_number > 0;
CREATE INDEX IF NOT EXISTS sc_series_episodes_order_idx
  ON sc_series_episodes(series_title_id, season_number, episode_number);

CREATE TABLE IF NOT EXISTS sc_keywords (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source text NOT NULL CHECK (source IN ('tmdb','provider','manual')),
  external_id text,
  name text NOT NULL,
  UNIQUE(source, external_id),
  UNIQUE(source, name)
);
CREATE TABLE IF NOT EXISTS sc_title_keywords (
  title_id bigint NOT NULL REFERENCES sc_titles(id) ON DELETE CASCADE,
  keyword_id bigint NOT NULL REFERENCES sc_keywords(id) ON DELETE CASCADE,
  PRIMARY KEY(title_id, keyword_id)
);
CREATE TABLE IF NOT EXISTS sc_genres (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source text NOT NULL CHECK (source IN ('tmdb','provider','manual')),
  external_id text,
  name text NOT NULL,
  UNIQUE(source, external_id),
  UNIQUE(source, name)
);
CREATE TABLE IF NOT EXISTS sc_title_genres (
  title_id bigint NOT NULL REFERENCES sc_titles(id) ON DELETE CASCADE,
  genre_id bigint NOT NULL REFERENCES sc_genres(id) ON DELETE CASCADE,
  PRIMARY KEY(title_id, genre_id)
);

