-- Episode titles are shared by language variants where series, season and episode match.
WITH ep AS (
  SELECT e.*, p.canonical_key AS series_key,
    CASE WHEN p.tmdb_id ~ '^[0-9]+$' THEN 'series:tmdb:'||p.tmdb_id ELSE 'series:provider:'||p.provider_id END AS resolved_series_key
  FROM sc_migration_stage e
  JOIN sc_migration_stage p ON p.kind='series' AND p.provider_id=e.parent_provider_id
  WHERE e.kind='episode'
), keyed_ep AS (
  SELECT ep.*,
    CASE WHEN COALESCE(ep.season_number,0)>0 AND COALESCE(ep.episode_number,0)>0
      THEN 'episode:'||ep.resolved_series_key||':s'||ep.season_number||':e'||ep.episode_number
      ELSE 'episode:provider:'||ep.provider_id END AS episode_key
  FROM ep
)
