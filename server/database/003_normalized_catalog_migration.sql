      WHEN lower(coalesce(e.language,'')) ~ '^(pt|por|portuguese)$' OR upper(coalesce(e.category_name,'')) LIKE '%|PT|%' OR upper(e.provider_name) ~ '(^|[^A-Z])(PT|POR|PORTUGUESE)([^A-Z]|$)' THEN 'pt'
      WHEN lower(coalesce(e.language,'')) ~ '^(ru|rus|russian)$' OR upper(coalesce(e.category_name,'')) LIKE '%|RU|%' OR upper(e.provider_name) ~ '(^|[^A-Z])(RU|RUS|RUSSIAN)([^A-Z]|$)' THEN 'ru'
