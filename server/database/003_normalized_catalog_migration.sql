WITH ep AS (
  SELECT e.*,
    CASE WHEN COALESCE(e.season_number,0)>0 AND COALESCE(e.episode_number,0)>0
      THEN 'episode:'||(CASE WHEN p.tmdb_id ~ '^[0-9]+$' THEN 'series:tmdb:'||p.tmdb_id ELSE 'series:provider:'||p.provider_id END)||':s'||e.season_number||':e'||e.episode_number
      ELSE 'episode:provider:'||e.provider_id END AS episode_key,
    CASE WHEN p.tmdb_id ~ '^[0-9]+$' THEN 'series:tmdb:'||p.tmdb_id ELSE 'series:provider:'||p.provider_id END AS series_key
  FROM sc_migration_stage e JOIN sc_migration_stage p ON p.kind='series' AND p.provider_id=e.parent_provider_id WHERE e.kind='episode'
)
INSERT INTO sc_series_episodes(episode_title_id,series_title_id,season_number,episode_number)
SELECT DISTINCT ON (et.id) et.id,st.id,COALESCE(ep.season_number,0),COALESCE(ep.episode_number,0)
FROM ep JOIN sc_titles et ON et.canonical_key=ep.episode_key JOIN sc_titles st ON st.canonical_key=ep.series_key
ORDER BY et.id,ep.id
ON CONFLICT(episode_title_id) DO NOTHING;

COMMIT;

