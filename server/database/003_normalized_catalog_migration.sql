      WHEN lower(coalesce(e.language,'')) ~ '^(de|ger|german|deutsch)$' OR upper(coalesce(e.category_name,'')) LIKE '%|DE|%' OR upper(e.provider_name) ~ '(^|[^A-Z])(DE|GER|GERMAN)([^A-Z]|$)' THEN 'de'
      WHEN lower(coalesce(e.language,'')) ~ '^(fr|fre|french|francais)$' OR upper(coalesce(e.category_name,'')) LIKE '%|FR|%' OR upper(e.provider_name) ~ '(^|[^A-Z])(FR|FRE|FRENCH)([^A-Z]|$)' THEN 'fr'
