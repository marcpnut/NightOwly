         CASE WHEN cat.value=s.category_id THEN COALESCE(NULLIF(s.category_name,''),cat.value) ELSE cat.value END
  FROM sc_migration_stage s CROSS JOIN LATERAL jsonb_array_elements_text(s.category_ids) cat(value)
)
