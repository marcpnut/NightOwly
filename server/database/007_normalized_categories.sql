-- Additive canonical category layer for movies and series.
-- Provider source categories and stream-category links are never modified.
-- Live/IPTV categories are explicitly excluded.
BEGIN;

CREATE TABLE IF NOT EXISTS sc_browse_categories (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind text NOT NULL CHECK (kind IN ('movie','series')),
  category_key text NOT NULL,
  category_type text NOT NULL CHECK (category_type IN ('genre','platform','quality','collection','other')),
  display_name text NOT NULL,
  sort_order smallint NOT NULL DEFAULT 100,
  UNIQUE(kind,category_key)
);

CREATE TABLE IF NOT EXISTS sc_browse_category_labels (
  browse_category_id bigint NOT NULL REFERENCES sc_browse_categories(id) ON DELETE CASCADE,
  language_code text NOT NULL REFERENCES sc_languages(code),
  display_name text NOT NULL,
  PRIMARY KEY(browse_category_id,language_code)
);

CREATE TABLE IF NOT EXISTS sc_browse_category_sources (
  browse_category_id bigint NOT NULL REFERENCES sc_browse_categories(id) ON DELETE CASCADE,
  source_category_id bigint NOT NULL REFERENCES sc_categories(id) ON DELETE CASCADE,
  mapping_method text NOT NULL,
  confidence text NOT NULL CHECK (confidence IN ('high','medium','review')),
  PRIMARY KEY(browse_category_id,source_category_id)
);
CREATE INDEX IF NOT EXISTS sc_browse_category_sources_source_idx
  ON sc_browse_category_sources(source_category_id,browse_category_id);

-- Normalize high-confidence translations and brand spelling variants. Each
-- provider category remains an alias; platform, quality, and family facets can
-- all point at the same source category without changing provider data.
CREATE TEMP TABLE sc_category_mapping_stage ON COMMIT DROP AS
WITH cleaned AS (
  SELECT c.id AS source_category_id,
         CASE WHEN c.kind='episode' THEN 'series' ELSE c.kind END AS kind,
         upper(btrim(COALESCE(
           substring(c.name from '^[[:space:]]*[|][A-Za-z]+[|][[:space:]]*(.*)$'),c.name
         ))) AS clean_name
  FROM sc_categories c
  WHERE c.kind IN ('movie','series','episode')
), aliases AS (
  SELECT *, CASE
    WHEN clean_name IN ('COMEDY','COMEDIES','KOMEDIE','KOMEDIES','COMEDY SERIES') THEN 'genre:comedy'
    WHEN clean_name IN ('DRAMA','DRAMAS','DRAMAT') THEN 'genre:drama'
    WHEN clean_name IN ('DOCUMENTARY','DOCUMENTARIES','DOCUMENTAIRE','DOCUMENTAIRES','DOKUMENTALNE') THEN 'genre:documentary'
    WHEN clean_name IN ('CHILDREN/FAMILY','CHILDREN & FAMILY','CHILDREN AND FAMILY','KINDEREN','FAMILIJNE') THEN 'genre:children-family'
    WHEN clean_name IN ('HORROR','HORROR/THRILLER') THEN 'genre:horror-thriller'
    WHEN clean_name IN ('DRAMA/ROMANCE','ROMANCE','ROMANS/MIŁOŚĆ') THEN 'genre:romance'
    WHEN clean_name IN ('WAR','WOJENNE') THEN 'genre:war'
    WHEN clean_name IN ('WESTERN','WESTERNS') THEN 'genre:western'
    WHEN clean_name IN ('CHRISTMAS MOVIES','KERSTFILMS','ŚWIĄTECZNE','NA ŚWIĄTECZNIE') THEN 'genre:christmas'
    WHEN clean_name ~* 'DISNEY[[:space:]]*[+]' THEN 'platform:disney-plus'
    WHEN clean_name ~* 'NETFLIX' THEN 'platform:netflix'
    WHEN clean_name ~* 'AMAZON[[:space:]]+PRIME|(^|[^A-Z])PRIME[[:space:]]*[+]' THEN 'platform:amazon-prime'
    WHEN clean_name ~* 'APPLE([[:space:]]+TV)?[[:space:]]*[+]' THEN 'platform:apple-tv-plus'
    WHEN clean_name ~* 'HBO([[:space:]]*MAX)?' THEN 'platform:hbo-max'
    WHEN clean_name ~* 'VIDEOLAND' THEN 'platform:videoland'
    WHEN clean_name ~* 'VIAPLAY' THEN 'platform:viaplay'
    WHEN clean_name ~* 'SKY[[:space:]]+SHOWTIME' THEN 'platform:sky-showtime'
    WHEN clean_name ~* 'PARAMOUNT[[:space:]]*[+]' THEN 'platform:paramount-plus'
    WHEN clean_name ~* 'PEACOCK' THEN 'platform:peacock'
    WHEN clean_name ~* 'HULU' THEN 'platform:hulu'
    WHEN clean_name ~* 'DISCOVERY[[:space:]]*(PLUS|[+])' THEN 'platform:discovery-plus'
    WHEN clean_name ~* '4K|2160P' THEN 'quality:4k'
    ELSE 'source:'||lower(clean_name)
  END AS primary_key
  FROM cleaned
), facets AS (
  SELECT source_category_id,kind,clean_name,primary_key AS category_key FROM aliases
  UNION
  SELECT source_category_id,kind,clean_name,'genre:children-family' FROM aliases
    WHERE clean_name ~* 'KIDS|CHILDREN|KINDEREN|FAMILIJNE|DZIECI'
      AND primary_key <> 'genre:children-family'
  UNION
  SELECT source_category_id,kind,clean_name,'quality:4k' FROM aliases
    WHERE clean_name ~* '4K|2160P' AND primary_key <> 'quality:4k'
), prepared AS (
SELECT source_category_id,kind,clean_name,category_key,
  CASE category_key
    WHEN 'genre:comedy' THEN 'Comedy' WHEN 'genre:drama' THEN 'Drama'
    WHEN 'genre:documentary' THEN 'Documentary' WHEN 'genre:children-family' THEN 'Children & Family'
    WHEN 'genre:horror-thriller' THEN 'Horror & Thriller' WHEN 'genre:romance' THEN 'Romance'
    WHEN 'genre:war' THEN 'War' WHEN 'genre:western' THEN 'Western' WHEN 'genre:christmas' THEN 'Christmas'
    WHEN 'platform:disney-plus' THEN 'Disney+'
    WHEN 'platform:netflix' THEN 'Netflix'
    WHEN 'platform:amazon-prime' THEN 'Amazon Prime Video'
    WHEN 'platform:apple-tv-plus' THEN 'Apple TV+'
    WHEN 'platform:hbo-max' THEN 'HBO Max'
    WHEN 'platform:videoland' THEN 'Videoland'
    WHEN 'platform:viaplay' THEN 'Viaplay'
    WHEN 'platform:sky-showtime' THEN 'SkyShowtime'
    WHEN 'platform:paramount-plus' THEN 'Paramount+'
    WHEN 'platform:peacock' THEN 'Peacock'
    WHEN 'platform:hulu' THEN 'Hulu'
    WHEN 'platform:discovery-plus' THEN 'Discovery+'
    WHEN 'quality:4k' THEN '4K'
    ELSE initcap(lower(clean_name))
  END AS display_name,
  CASE WHEN category_key LIKE 'genre:%' THEN 'genre'
       WHEN category_key LIKE 'platform:%' THEN 'platform'
       WHEN category_key LIKE 'quality:%' THEN 'quality'
       WHEN clean_name ~* 'NEW RELEASE|LATEST|RECENT|TOP IMDB|OSCAR|PRE-RELEASE|COLLECTION|(^|[^0-9])20[0-9]{2}([^0-9]|$)' THEN 'collection'
       ELSE 'other' END AS category_type,
  CASE WHEN category_key LIKE 'genre:%' THEN 10
       WHEN category_key LIKE 'platform:%' THEN 30
       WHEN category_key LIKE 'quality:%' THEN 40
       WHEN clean_name ~* 'NEW RELEASE|LATEST|RECENT|TOP IMDB|OSCAR|PRE-RELEASE|COLLECTION|(^|[^0-9])20[0-9]{2}([^0-9]|$)' THEN 50
       ELSE 100 END::smallint AS sort_order,
  CASE WHEN category_key LIKE 'genre:%' OR category_key LIKE 'platform:%' OR category_key LIKE 'quality:%' THEN 'high' ELSE 'review' END AS confidence,
  CASE WHEN category_key LIKE 'genre:%' THEN 'translated_or_synonymous_label'
       WHEN category_key LIKE 'platform:%' THEN 'brand_variant'
       WHEN category_key LIKE 'quality:%' THEN 'quality_facet'
       ELSE 'stripped_source_label' END AS mapping_method
FROM facets
)
SELECT DISTINCT * FROM prepared;

INSERT INTO sc_browse_categories(kind,category_key,category_type,display_name,sort_order)
SELECT DISTINCT kind,category_key,category_type,display_name,sort_order
FROM sc_category_mapping_stage
ON CONFLICT(kind,category_key) DO UPDATE SET
  category_type=EXCLUDED.category_type,display_name=EXCLUDED.display_name,sort_order=EXCLUDED.sort_order;

-- Rebuild only the generated mappings for movie/series/episode categories;
-- Live/IPTV source categories are never deleted or remapped.
DELETE FROM sc_browse_category_sources bs USING sc_categories c
WHERE c.id=bs.source_category_id AND c.kind IN ('movie','series','episode');

INSERT INTO sc_browse_category_sources(browse_category_id,source_category_id,mapping_method,confidence)
SELECT b.id,s.source_category_id,s.mapping_method,s.confidence
FROM sc_category_mapping_stage s
JOIN sc_browse_categories b ON b.kind=s.kind AND b.category_key=s.category_key
ON CONFLICT(browse_category_id,source_category_id) DO UPDATE SET
  mapping_method=EXCLUDED.mapping_method,confidence=EXCLUDED.confidence;

DELETE FROM sc_browse_categories b
WHERE NOT EXISTS (SELECT 1 FROM sc_browse_category_sources s WHERE s.browse_category_id=b.id);

